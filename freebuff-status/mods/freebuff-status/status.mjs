#!/usr/bin/env node
/**
 * Install, remove and inspect the Freebuff -> Herdr bridge.
 *
 *   node status.mjs install      write the `freebuff` wrapper and register the
 *                                program in Herdr's programs.json
 *   node status.mjs uninstall    remove only files this package wrote
 *   node status.mjs doctor       JSON: what is installed and what is missing
 *   node status.mjs path         JSON: the exact paths used
 *
 * The mod folder itself is copied by the repo's install.sh (or by hand). This
 * script only touches `~/.local/bin/freebuff` and `~/.config/herdr-app/programs.json`.
 */

import {
  chmodSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { delimiter, dirname, join } from "node:path";

const VERSION = "1.0.0";
const MARKER = "# freebuff-status wrapper";
const PROGRAM = {
  name: "Freebuff",
  icon: "mods/freebuff-status/robot.svg",
  tint: true,
  run: ["freebuff"],
};

const home = process.env.HOME || homedir();
const configDir =
  process.env.HERDR_CONFIG_DIR ||
  join(process.env.XDG_CONFIG_HOME || join(home, ".config"), "herdr-app");
const modsDir = join(configDir, "mods");
const modDir = join(modsDir, "freebuff-status");
const watcherPath = join(modDir, "freebuff-watcher.mjs");
const statusPath = join(modDir, "status.mjs");
const wrapperPath = process.env.FREEBUFF_WRAPPER || join(home, ".local", "bin", "freebuff");
const programsPath = join(configDir, "programs.json");
const legacyWatcherPath = join(configDir, "freebuff-watcher.js");

const args = process.argv.slice(2);
const force = args.includes("--force");
const command = args.find((arg) => !arg.startsWith("-")) || "doctor";

function shellQuote(value) {
  return `'${String(value).replace(/'/g, "'\\''")}'`;
}

/**
 * The wrapper shadows `freebuff` in PATH. It finds the real binary (skipping
 * itself), starts the watcher only inside Herdr, and then execs Freebuff so the
 * process id stays the same: the watcher follows that pid.
 */
function wrapperScript() {
  return [
    "#!/usr/bin/env bash",
    `${MARKER} v${VERSION}`,
    "# Generated by status.mjs install. Remove it with:",
    `#   node ${shellQuote(statusPath)} uninstall`,
    "set -euo pipefail",
    "",
    `WATCHER=${shellQuote(watcherPath)}`,
    "",
    'self_dir="$(cd "$(dirname "$0")" && pwd -P)"',
    'self="$self_dir/$(basename "$0")"',
    "",
    'real=""',
    'IFS=\':\' read -r -a dirs <<< "${PATH:-}"',
    'for dir in "${dirs[@]}"; do',
    '  [ -n "$dir" ] || dir="."',
    '  candidate="$dir/freebuff"',
    '  if [ ! -x "$candidate" ] || [ -d "$candidate" ]; then',
    "    continue",
    "  fi",
    '  candidate_dir="$(cd "$dir" 2>/dev/null && pwd -P)" || continue',
    '  if [ "$candidate_dir/$(basename "$candidate")" = "$self" ]; then',
    "    continue",
    "  fi",
    '  real="$candidate"',
    "  break",
    "done",
    "",
    'if [ -z "$real" ]; then',
    "  printf 'freebuff: real freebuff binary not found in PATH\\n' >&2",
    "  exit 1",
    "fi",
    "",
    'if [ -n "${HC_TERMINAL_ID:-}" ] && [ -f "$WATCHER" ]; then',
    '  log_dir="${XDG_STATE_HOME:-$HOME/.local/state}/freebuff-status"',
    '  mkdir -p "$log_dir" 2>/dev/null || true',
    '  HERDR_FREEBUFF_PID=$$ node "$WATCHER" >/dev/null 2>>"$log_dir/watcher.log" &',
    "fi",
    "",
    'exec "$real" "$@"',
    "",
  ].join("\n");
}

function readPrograms() {
  if (!existsSync(programsPath)) return { data: { programs: {} }, existed: false, valid: true };
  try {
    return { data: JSON.parse(readFileSync(programsPath, "utf8")), existed: true, valid: true };
  } catch {
    return { data: null, existed: true, valid: false };
  }
}

function writePrograms(data) {
  mkdirSync(dirname(programsPath), { recursive: true });
  writeFileSync(programsPath, `${JSON.stringify(data, null, 2)}\n`);
}

function sameProgram(value) {
  return JSON.stringify(value) === JSON.stringify(PROGRAM);
}

/** An entry this package wrote, with or without a key added since then. */
function looksOurs(value) {
  return (
    Boolean(value) &&
    value.name === PROGRAM.name &&
    Array.isArray(value.run) &&
    value.run.length === 1 &&
    value.run[0] === "freebuff"
  );
}

/**
 * Adds the keys a previous version did not write (the icon) without touching
 * the ones the person set, and keeps `PROGRAM`'s key order so `sameProgram`
 * still recognises the result.
 */
function mergeProgram(entry) {
  const next = {};
  for (const key of Object.keys(PROGRAM)) next[key] = key in entry ? entry[key] : PROGRAM[key];
  for (const key of Object.keys(entry)) if (!(key in next)) next[key] = entry[key];
  return next;
}

function realFreebuff() {
  const wrapperDir = dirname(wrapperPath);
  for (const dir of (process.env.PATH || "").split(delimiter)) {
    const candidate = join(dir || ".", "freebuff");
    try {
      if (!statSync(candidate).isFile()) continue;
    } catch {
      continue;
    }
    if (dirname(candidate) === wrapperDir) continue;
    return candidate;
  }
  return null;
}

function inPath(dir) {
  return (process.env.PATH || "").split(delimiter).includes(dir);
}

function removeLegacyWatcher() {
  if (!existsSync(legacyWatcherPath)) return false;
  let text = "";
  try {
    text = readFileSync(legacyWatcherPath, "utf8");
  } catch {
    return false;
  }
  if (!text.includes('PLUGIN_ID = "herdr-freebuff-status"')) {
    console.warn(`Left ${legacyWatcherPath} alone: it is not this mod's old watcher.`);
    return false;
  }
  rmSync(legacyWatcherPath);
  return true;
}

function install() {
  if (!existsSync(watcherPath)) {
    console.warn(`Warning: ${watcherPath} is missing. Copy the mod folder first.`);
  }

  mkdirSync(dirname(wrapperPath), { recursive: true });
  if (existsSync(wrapperPath)) {
    const current = readFileSync(wrapperPath, "utf8");
    if (!current.includes(MARKER)) {
      const backup = `${wrapperPath}.freebuff-status-backup`;
      if (!existsSync(backup)) {
        copyFileSync(wrapperPath, backup);
        console.log(`Backed up the existing wrapper to ${backup}`);
      }
    }
  }
  writeFileSync(wrapperPath, wrapperScript());
  chmodSync(wrapperPath, 0o755);
  console.log(`Installed wrapper: ${wrapperPath}`);

  const { data, valid } = readPrograms();
  if (!valid) {
    console.warn(`Warning: ${programsPath} is not valid JSON; add the freebuff program by hand.`);
  } else {
    data.programs = data.programs && typeof data.programs === "object" ? data.programs : {};
    const current = data.programs.freebuff;
    if (!current) {
      data.programs.freebuff = { ...PROGRAM };
      writePrograms(data);
      console.log(`Registered freebuff in ${programsPath}`);
    } else if (looksOurs(current)) {
      const next = mergeProgram(current);
      if (JSON.stringify(next) !== JSON.stringify(current)) {
        data.programs.freebuff = next;
        writePrograms(data);
        console.log(`Updated the freebuff entry in ${programsPath} (icon)`);
      }
    } else {
      console.warn(`Left the freebuff entry in ${programsPath} alone: it was not written by this mod.`);
    }
  }

  if (removeLegacyWatcher()) {
    console.log(`Removed the old watcher: ${legacyWatcherPath}`);
  }
  if (existsSync(join(modsDir, "freebuff"))) {
    console.warn(`Old mod folder found: ${join(modsDir, "freebuff")}`);
    console.warn(`Remove it with: rm -rf ${shellQuote(join(modsDir, "freebuff"))}`);
  }
  if (!inPath(dirname(wrapperPath))) {
    console.warn(`Warning: ${dirname(wrapperPath)} is not in PATH, so the wrapper will not be used.`);
  }

  console.log("");
  console.log("Next: restart Freebuff, or start a new `freebuff` in a Herdr terminal.");
  console.log(`Check it with: node ${shellQuote(statusPath)} doctor`);
}

function uninstall() {
  if (existsSync(wrapperPath)) {
    const current = readFileSync(wrapperPath, "utf8");
    if (!current.includes(MARKER) && !force) {
      console.warn(`Left ${wrapperPath} alone: it is not this mod's wrapper (use --force).`);
    } else {
      rmSync(wrapperPath);
      console.log(`Removed wrapper: ${wrapperPath}`);
    }
  }

  const { data, valid } = readPrograms();
  if (valid && sameProgram(data?.programs?.freebuff)) {
    delete data.programs.freebuff;
    writePrograms(data);
    console.log(`Removed freebuff from ${programsPath}`);
  }

  if (removeLegacyWatcher()) {
    console.log(`Removed the old watcher: ${legacyWatcherPath}`);
  }

  console.log("");
  console.log(`The mod folder is still there. Remove it with: rm -rf ${shellQuote(modDir)}`);
}

function doctor() {
  const { data, valid } = readPrograms();
  let wrapper = null;
  try {
    wrapper = readFileSync(wrapperPath, "utf8");
  } catch {
    wrapper = null;
  }
  const real = realFreebuff();

  return {
    installed: existsSync(watcherPath),
    wrapper: wrapper !== null,
    wrapperOurs: wrapper?.includes(MARKER) ?? false,
    upToDate: wrapper !== null && wrapper === wrapperScript(),
    program: Boolean(valid && data?.programs?.freebuff),
    programCustomised: Boolean(valid && data?.programs?.freebuff && !sameProgram(data.programs.freebuff)),
    wrapperInPath: inPath(dirname(wrapperPath)),
    legacyMod: existsSync(join(modsDir, "freebuff")),
    legacyWatcher: existsSync(legacyWatcherPath),
    inHerdr: Boolean(process.env.HC_TERMINAL_ID),
    node: process.version,
    freebuff: real,
    modDir,
    wrapperPath,
    watcherPath,
    programsPath,
    restart: "Restart Freebuff (or start a new terminal) after installing.",
  };
}

function paths() {
  return {
    modDir,
    watcherPath,
    statusPath,
    wrapperPath,
    programsPath,
    configDir,
    legacyWatcherPath,
  };
}

switch (command) {
  case "install":
    install();
    break;
  case "uninstall":
    uninstall();
    break;
  case "doctor":
    console.log(JSON.stringify(doctor(), null, 2));
    break;
  case "path":
    console.log(JSON.stringify(paths(), null, 2));
    break;
  default:
    console.error(`Unknown command: ${command}`);
    console.error("Usage: node status.mjs [install|uninstall|doctor|path] [--force]");
    process.exitCode = 1;
}
